import asyncio, sys
from playwright.async_api import async_playwright
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(executable_path='/usr/bin/google-chrome', args=['--no-sandbox'])
        ctx = await b.new_context(viewport={'width':390,'height':844}, device_scale_factor=2, is_mobile=True, has_touch=True)
        pg = await ctx.new_page()
        errs=[]
        pg.on('pageerror', lambda e: errs.append(str(e)))
        pg.on('console', lambda m: errs.append('console:'+m.text) if m.type=='error' else None)
        await pg.goto('http://localhost:8765/')
        await pg.wait_for_timeout(800)
        await pg.screenshot(path='test/01-signin.png')
        await pg.click('text=Jake')
        await pg.wait_for_timeout(500)
        await pg.screenshot(path='test/02-doctor.png', full_page=True)
        # type an utterance
        await pg.fill('#say', 'blue 42 104.6 drax')
        await pg.press('#say', 'Enter')
        await pg.wait_for_timeout(300)
        await pg.screenshot(path='test/03-filled.png', full_page=True)
        await pg.click('button.save')
        await pg.wait_for_timeout(400)
        await pg.screenshot(path='test/04-location.png')
        await pg.click('.modal .chip >> nth=0')
        await pg.wait_for_timeout(400)
        await pg.screenshot(path='test/05-saved.png', full_page=True)
        # repull same calf with HR1 -> warning
        await pg.fill('#say', 'blue 42 104.9 drax')
        await pg.press('#say', 'Enter')
        await pg.wait_for_timeout(300)
        await pg.screenshot(path='test/06-warning.png', full_page=True)
        await pg.click('button.save')
        await pg.wait_for_timeout(300)
        # validation
        await pg.click('button.save')
        await pg.wait_for_timeout(300)
        await pg.screenshot(path='test/07-validation.png')
        await pg.click('text=Tag lookup')
        await pg.fill('.tagnum', '42')
        await pg.wait_for_timeout(300)
        await pg.screenshot(path='test/08-lookup.png', full_page=True)
        await pg.click('text=Reports')
        await pg.click('text=Season')
        await pg.wait_for_timeout(300)
        await pg.screenshot(path='test/09-reports.png', full_page=True)
        await pg.click('nav >> text=More')
        await pg.wait_for_timeout(300)
        await pg.screenshot(path='test/10-more.png', full_page=True)
        print('errors:', errs)
        await b.close()
asyncio.run(main())
